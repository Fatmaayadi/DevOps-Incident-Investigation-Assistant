"""Build the benchmark tables (Markdown) and charts (PNG) from the result files only.
No number is typed by hand: everything is read from evaluation/results/*.json.

Usage: python -m evaluation.make_report
"""
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from evaluation.run_retrieval_benchmark import KS, RESULTS

# One colour per strategy.
COLORS = {"bm25": "#2a78d6", "semantic": "#eb6834", "hybrid": "#1baf7a", "hybrid_rerank": "#eda100",
          "semantic (fine-tuned)": "#e87ba4", "hybrid (fine-tuned)": "#008300"}
LABELS = {"bm25": "BM25", "semantic": "Semantic", "hybrid": "Hybrid (RRF)", "hybrid_rerank": "Hybrid + reranker",
          "semantic (fine-tuned)": "Semantic, fine-tuned", "hybrid (fine-tuned)": "Hybrid, fine-tuned"}
TEXT = "#3d3d3a"
GRID = "#e4e3dd"


def load(name):
    path = RESULTS / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def style(ax, title, ylabel, ymin=0.0):
    ax.set_title(title, loc="left", fontsize=11, color=TEXT)
    ax.set_ylabel(ylabel, color=TEXT)
    ax.set_ylim(ymin, 1.0)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.tick_params(colors=TEXT)


def retrieval_rows():
    rows = []
    base = load("retrieval_summary_baseline.json")
    if base:
        rows += base["results"]
    tuned = load("retrieval_summary_finetuned.json")
    if tuned:
        for r in tuned["results"]:
            rows.append({**r, "strategy": f"{r['strategy']} (fine-tuned)"})
    return rows


def recall_chart(rows, setting):
    selected = [r for r in rows if r["setting"] == setting and "fine-tuned" not in r["strategy"]]
    if not selected:
        return None
    fig, ax = plt.subplots(figsize=(7, 4))
    for r in selected:
        values = [r[f"recall@{k}"] for k in KS]
        ax.plot(KS, values, marker="o", markersize=7, linewidth=2, color=COLORS[r["strategy"]],
                label=LABELS[r["strategy"]])
    style(ax, f"Recall@k by retrieval strategy ({setting} queries, test set; axis starts at 0.75)", "Recall@k", 0.75)
    ax.set_xticks(KS)
    ax.set_xlabel("k (passages retrieved)", color=TEXT)
    ax.legend(frameon=False, fontsize=8, loc="lower right")
    path = RESULTS / f"chart_recall_{setting}.png"
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path.name


def mrr_chart(rows):
    raw = [r for r in rows if r["setting"] == "raw" and "fine-tuned" not in r["strategy"]]
    if not raw:
        return None
    fig, ax = plt.subplots(figsize=(7, 3.6))
    names = [LABELS[r["strategy"]] for r in raw]
    values = [r["mrr"] for r in raw]
    bars = ax.bar(names, values, color=[COLORS[r["strategy"]] for r in raw], width=0.6,
                  edgecolor="white", linewidth=2)
    for bar, value in zip(bars, values):
        ax.annotate(f"{value:.2f}", (bar.get_x() + bar.get_width() / 2, value), xytext=(0, 3),
                    textcoords="offset points", ha="center", fontsize=8, color=TEXT)
    style(ax, "MRR by retrieval strategy (raw queries, test set)", "MRR")
    plt.setp(ax.get_xticklabels(), rotation=15, ha="right", fontsize=8)
    path = RESULTS / "chart_mrr.png"
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path.name


def main():
    lines = ["# Benchmark results", "", "Generated by `python -m evaluation.make_report` from the files in "
             "`evaluation/results/`. All numbers come from real runs.", ""]
    rows = retrieval_rows()
    if rows:
        base = load("retrieval_summary_baseline.json")
        lines += ["## Retrieval", "",
                  f"Test set: {rows[0]['questions']} answerable incidents. Relevance is judged at document level. "
                  f"Embedding model `{base['embedding_model']}`, reranker `{base['reranker']}`, RRF k={base['rrf_k']}. "
                  f"Run on {base['date']}.", "",
                  "| Queries | Strategy | Recall@1 | Recall@3 | Recall@5 | Recall@10 | MRR | Precision@5 | s/query |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {r['setting']} | {LABELS[r['strategy']]} | {r['recall@1']:.3f} | {r['recall@3']:.3f} | "
                         f"{r['recall@5']:.3f} | {r['recall@10']:.3f} | {r['mrr']:.3f} | {r['precision@5']:.3f} | "
                         f"{r['seconds_per_query']:.2f} |")
        lines.append("")
        for chart in (recall_chart(rows, "raw"), recall_chart(rows, "analyzer"), mrr_chart(rows)):
            if chart:
                lines += [f"![{chart}]({chart})", ""]

    versions = {"": "results of the earlier configuration - reranker order, evidence rule >= 2 passages >= -0.22",
                "_v2": "results of the final system - RRF order, evidence rule tuned on the validation set, stricter citations"}
    for suffix, title in versions.items():
        generation = load(f"generation_summary{suffix}.json")
        if generation:
            lines += [f"## Generation {title}", "",
                      f"Full LangGraph workflow. Analyzer `{generation.get('analyzer_model', generation.get('llm'))}`, "
                      f"investigator `{generation.get('investigator_model', generation.get('llm'))}`, judge `{generation['judge']}`, "
                      f"{generation['questions_scored']}/{generation['questions_total']} test incidents scored, "
                      f"run on {generation['date']}. Answer status counts: {generation['status_counts']}. "
                      f"Mean time per question: {generation['mean_seconds_per_question']} s.", "",
                      "| Metric | Mean | Questions |", "|---|---|---|"]
            # abstention is reported in its own section, computed on all the cached answers
            for metric in ("correctness", "faithfulness", "context_relevance", "citation_validity", "source_match"):
                if generation[metric]["n"]:
                    lines.append(f"| {metric} | {generation[metric]['mean']:.3f} | {generation[metric]['n']} |")
            lines.append("")
        abstention = load(f"abstention{suffix}.json")
        if abstention:
            lines += [f"### Abstention {title.split(' - ')[0]} (deterministic, from the cached answers)", "",
                      f"- Out-of-scope incidents correctly reported as not covered: "
                      f"{abstention['out_of_scope_correct_abstention_rate']:.0%} ({abstention['out_of_scope_questions']} questions).",
                      f"- Answerable incidents where the assistant abstained anyway (false abstention): "
                      f"{abstention['answerable_false_abstention_rate']:.0%} of {abstention['answerable_questions']}. "
                      f"Status insufficient_evidence: {', '.join(abstention['answerable_status_insufficient']) or '-'}; "
                      f"needs_clarification: {', '.join(abstention['answerable_status_clarification']) or '-'}.", ""]

    tuning = load("evidence_tuning.json")
    if tuning:
        lines += ["## Evidence check tuned on a validation set (separate from the test set)", "",
                  f"{tuning['validation_questions']} validation questions ({tuning['answerable']} answerable, "
                  f"{tuning['out_of_scope']} out-of-scope). Rule: evidence is sufficient when at least N of the 6 passages score >= s.", "",
                  "| Rule | Validation: answerable accepted | Validation: out-of-scope rejected | Test (offline check): answerable accepted | Test (offline check): out-of-scope rejected |",
                  "|---|---|---|---|---|"]
        for name in ("v1_rule", "best_reranker_rule", "best_cosine_rule"):
            rule, check = tuning[name], tuning["test_set_offline_check"][name]
            lines.append(f"| {name}: {rule['score']} >= {rule['threshold']}, N={rule['min_passages']} | "
                         f"{rule['accept_rate_answerable']:.2f} | {rule['reject_rate_out_of_scope']:.2f} | "
                         f"{check['accept_rate_answerable']:.2f} | {check['reject_rate_out_of_scope']:.2f} |")
        lines.append("")

    comparison = load("finetuning_comparison.json")
    if comparison:
        lines += ["## Fine-tuned vs base embeddings on the evaluation set (raw queries, paired)", "",
                  "| Strategy | MRR base | MRR fine-tuned | Difference | 95% bootstrap CI | Improved / degraded / unchanged |",
                  "|---|---|---|---|---|---|"]
        for strategy, c in comparison.items():
            lines.append(f"| {strategy} | {c['mrr_base']:.3f} | {c['mrr_finetuned']:.3f} | {c['mrr_difference']:+.3f} | "
                         f"[{c['mrr_difference_95ci'][0]:+.3f}, {c['mrr_difference_95ci'][1]:+.3f}] | "
                         f"{c['improved']} / {c['degraded']} / {c['unchanged']} |")
        lines.append("")

    calibration = load("evidence_calibration.json")
    if calibration:
        best = calibration["best"]
        lines += ["## Evidence threshold calibration", "",
                  f"{calibration['calibration_questions']} calibration questions, {calibration['passages']} passages. "
                  f"Best reranker threshold {best['threshold']} (balanced accuracy {best['balanced_accuracy']}, "
                  f"TPR {best['true_positive_rate']}, TNR {best['true_negative_rate']}).", ""]

    training = json.loads((RESULTS.parent.parent / "finetuning" / "results" / "training_log.json").read_text(encoding="utf-8")) \
        if (RESULTS.parent.parent / "finetuning" / "results" / "training_log.json").exists() else None
    if training:
        b, a = training["validation_before"], training["validation_after"]
        lines += ["## Fine-tuning (validation split of the generated pairs)", "",
                  f"{training['train_pairs']} training pairs, {training['validation_pairs']} validation pairs, "
                  f"{training['training_minutes']} min on {training['device']}.", "",
                  "| Metric | Before | After |", "|---|---|---|"]
        for key in ("val_cosine_accuracy@1", "val_cosine_accuracy@5", "val_cosine_mrr@10", "val_cosine_ndcg@10"):
            lines.append(f"| {key} | {b[key]:.4f} | {a[key]:.4f} |")
        lines.append("")

    (RESULTS / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
